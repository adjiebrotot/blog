"""A figure: title, subtitle, drawing (wide + narrow layouts), source line, note, data table.

    fig = Figure('gsl-pi-real-wages',
                 title={'en': 'Real wages have not recovered from 2021', 'id': '...'},
                 subtitle={'en': 'Average real wage, index 2019 = 100', 'id': '...'},
                 source={'en': 'BPS Sakernas (August); author calculations', 'id': '...'},
                 alt={'en': 'Line chart ...', 'id': '...'},
                 review={...})          # answers to the manual checklist items (references/checklist.md)
    fig.add(Line(...))                 # components stack top to bottom
    # or: @fig.draw  def draw(c, lang): ...   for a free composition on the canvas

Text that differs by language is a dict {'en': ..., 'id': ...}; plain strings are used as-is.
The page shows the title and subtitle as HTML above the drawing (they reflow, translate and
read aloud like the post), the drawing as two inline SVGs (wide >= 520px column, narrow
below; CSS shows one), then the source, the note and a folded data table.
"""
from . import metrics
from .canvas import Canvas, esc, MIN_TEXT

LAYOUTS = (('w', 720), ('n', 280))
I18N = {'source': 'chart_source', 'note': 'chart_note', 'data': 'chart_data'}


def tr(v, lang):
    """Pick the language from a {'en':..., 'id':...} dict; anything else as it is."""
    if isinstance(v, dict) and ('en' in v or 'id' in v):
        return v.get(lang, v.get('en'))
    return v


class Component:
    """Base class: a component draws itself at the canvas' current y and returns the new y."""
    legend = False

    def draw(self, c, lang, y):
        raise NotImplementedError

    def table(self, lang):
        """Rows for the data table: (header, rows) or None."""
        return None

    def value_labels(self):
        return []


class Figure:
    def __init__(self, name, title, subtitle=None, source=None, note=None, alt=None, langs=('en', 'id'),
                 layouts=LAYOUTS, data_table=True, review=None, kind='chart', gap=18):
        self.name, self.title, self.subtitle = name, title, subtitle
        self.source, self.note, self.alt = source, note, alt
        self.langs, self.layouts = langs, layouts
        self.data_table, self.review, self.kind, self.gap = data_table, review or {}, kind, gap
        self.parts, self.fn = [], None
        self.last = {}   # lang -> {layout: canvas}

    def add(self, part):
        self.parts.append(part)
        return part

    def draw(self, fn):
        self.fn = fn
        return fn

    # ── rendering ──────────────────────────────────────────────────────
    def canvas(self, lang, layout, W):
        c = Canvas(W, layout, lang)
        c.idp = f'pi-{self.name}-{layout}-'
        y = 0
        for i, p in enumerate(self.parts):
            if i:
                y += self.gap
            y = p.draw(c, lang, y)
        if self.fn:
            r = self.fn(c, lang)
            if isinstance(r, (int, float)):
                c.H = r
        return c

    def svgs(self, lang):
        out, self.last[lang] = [], {}
        for layout, W in self.layouts:
            c = self.canvas(lang, layout, W)
            self.last[lang][layout] = c
            cls = f'pi-{layout}'
            out.append(c.svg(cls, tr(self.title, lang), tr(self.alt, lang) or tr(self.title, lang))
                       .replace(f'id="{cls}-t"', f'id="pi-{self.name}-{layout}-t"')
                       .replace(f'id="{cls}-d"', f'id="pi-{self.name}-{layout}-d"')
                       .replace(f'aria-labelledby="{cls}-t {cls}-d"',
                                f'aria-labelledby="pi-{self.name}-{layout}-t pi-{self.name}-{layout}-d"'))
        return out

    def html(self, lang):
        n = self.name
        i18n = f'site.data.i18n.{lang}'
        head = f'<strong>{esc(tr(self.title, lang))}</strong>'
        if self.subtitle:
            head += f'<span>{esc(tr(self.subtitle, lang))}</span>'
        art = ''.join(self.svgs(lang))
        foot = ''
        if self.source:
            foot += f'<span>{{{{ {i18n}.chart_source }}}}: {esc(tr(self.source, lang))}</span>'
        if self.note:
            foot += f'<span class="pi-note">{{{{ {i18n}.chart_note }}}}: {esc(tr(self.note, lang))}</span>'
        table = ''
        if self.data_table:
            t = self.table_html(lang)
            if t:
                table = (f'<details class="pi-data"><summary>{{{{ {i18n}.chart_data }}}}</summary>{t}</details>')
        return ('{%- comment -%} Generated by the procedural-illustration skill from '
                f'_illustrations/{n}.py. Edit the spec and run render.py --publish; never edit this file. '
                '{%- endcomment -%}\n'
                f'<figure class="pi pi-{self.kind}" id="pi-{n}" role="group" aria-labelledby="pi-{n}-h">'
                f'<figcaption id="pi-{n}-h">{head}</figcaption>'
                f'<div class="pi-art">{art}</div>'
                + (f'<p class="pi-src">{foot}</p>' if foot else '') + table + '</figure>\n')

    def table_html(self, lang):
        for p in self.parts:
            t = p.table(lang)
            if t:
                head, rows = t
                th = ''.join(f'<th scope="col">{esc(h)}</th>' for h in head)
                body = ''
                for r in rows:
                    cells = ''
                    for j, v in enumerate(r):
                        if j == 0:
                            cells += f'<th scope="row">{esc(v)}</th>'
                        else:
                            cells += f'<td class="n">{esc(v)}</td>'
                    body += f'<tr>{cells}</tr>'
                return f'<table><thead><tr>{th}</tr></thead><tbody>{body}</tbody></table>'
        return None

    # ── checks that need the drawing (the rest live in check.py) ───────
    def drawing_issues(self, lang):
        out = []
        for layout, c in self.last.get(lang, {}).items():
            out += [(lv, f'[{lang}/{layout}] {m}') for lv, m in c.issues]
            ts = c.texts
            for t in ts:
                if t['size'] < MIN_TEXT[layout] - 1e-6:
                    out.append(('ERROR', f'[{lang}/{layout}] text "{t["text"][:40]}" is {t["size"]}px, under '
                                         f'{MIN_TEXT[layout]}px (item 4)'))
                x0, y0, x1, y1 = t['box']
                if x0 < -0.5 or x1 > c.W + 0.5:
                    out.append(('ERROR', f'[{lang}/{layout}] text "{t["text"][:40]}" runs outside the frame '
                                         f'({x0:.0f}..{x1:.0f} of {c.W})'))
            from .canvas import seg_box
            for t in ts:
                b = t['box']
                if t['kind'] in ('label', 'note', 'value', 'legend') and any(
                        seg_box(x1, y1, x2, y2, (b[0] + 1, b[1] + 1, b[2] - 1, b[3] - 1)) for (x1, y1), (x2, y2) in c.segs):
                    out.append(('WARN', f'[{lang}/{layout}] a data line runs through "{t["text"][:30]}" (item 9)'))
            for i in range(len(ts)):
                for j in range(i + 1, len(ts)):
                    a, b = ts[i]['box'], ts[j]['box']
                    ox = min(a[2], b[2]) - max(a[0], b[0])
                    oy = min(a[3], b[3]) - max(a[1], b[1])
                    if ox > 0.5 and oy > 0.5:
                        out.append(('ERROR', f'[{lang}/{layout}] text overlaps: "{ts[i]["text"][:30]}" and '
                                             f'"{ts[j]["text"][:30]}" (item 9)'))
        return out
